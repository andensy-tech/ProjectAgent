const API_BASE = import.meta.env.VITE_API_URL || ''

/** Shared auth header builder for all API calls. */
export function getAuthHeaders(): Record<string, string> {
  return {
    'Content-Type': 'application/json',
    Authorization: `Bearer ${localStorage.getItem('token') || ''}`,
  }
}

/** Redirect to login on 401. */
function handleUnauthorized() {
  localStorage.removeItem('token')
  // Clear zustand persist storage
  localStorage.removeItem('auth-storage')
  window.location.href = '/login'
}

/** Generic fetch wrapper with auth headers. */
export async function apiFetch<T = any>(url: string, options?: RequestInit): Promise<T> {
  const fullUrl = `${API_BASE}${url}`
  const response = await fetch(fullUrl, {
    ...options,
    headers: {
      ...getAuthHeaders(),
      ...(options?.headers || {}),
    },
  })
  if (response.status === 401) {
    handleUnauthorized()
    throw new Error('未登录或登录已过期')
  }
  if (!response.ok) throw new Error(`API error: ${response.status} ${response.url}`)

  const ct = response.headers.get('content-type') || ''
  // If response is not JSON, throw immediately with diagnostic info
  if (!ct.includes('application/json')) {
    const bodyStart = await response.clone().text().then(t => t.substring(0, 120))
    throw new Error(
      `非JSON响应: ${response.url} (${response.status}), Content-Type: ${ct}, 响应开头: ${bodyStart}`,
    )
  }

  return response.json()
}

