/** Agent 产出文件描述（与后端 app/services/file_outputs.py 输出结构一致）。 */
export interface FileDownload {
  file_name: string
  file_path?: string
  size?: number
  skill_name?: string
  download_url: string
}

/**
 * 从技能/工具执行结果中取出可下载文件。
 *
 * 后端的 `result.files[]`（含签名下载链接）是权威来源；旧结构
 * （`result.file_path` / `result.data.file_path` + skill_name）作为兜底，
 * 退回技能目录下载接口（同样走鉴权下载）。
 */
export function extractFileDownload(result: any): FileDownload | undefined {
  const files = result?.files
  if (Array.isArray(files) && files.length > 0 && files[0]?.download_url) {
    return files[0] as FileDownload
  }
  const filePath: string | undefined = result?.file_path || result?.data?.file_path
  const skillName: string | undefined = result?.skill_name || result?.data?.skill_name
  if (filePath && skillName) {
    const fileName = filePath.split(/[/\\]/).pop() || filePath
    return {
      file_name: fileName,
      file_path: filePath,
      skill_name: skillName,
      download_url: `/api/skills/${encodeURIComponent(skillName)}/download?file=${encodeURIComponent(fileName)}`,
    }
  }
  return undefined
}

/**
 * Upload a file and return the file_id.
 */
export async function uploadFile(file: File): Promise<{ file_id: string; file_name: string }> {
  const formData = new FormData()
  formData.append('file', file)
  const response = await fetch(`${API_BASE}/api/upload`, {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${localStorage.getItem('token') || ''}`,
    },
    body: formData,
  })
  if (response.status === 401) {
    handleUnauthorized()
    throw new Error('未登录或登录已过期')
  }
  if (!response.ok) throw new Error(`Upload failed: ${response.status}`)
  return response.json()
}

/**
 * Download a file generated by the Agent.
 *
 * 下载接口需要 JWT，而 <a href> 不会带 Authorization 头，因此这里用带鉴权的
 * fetch 拉取 blob 后触发浏览器下载。
 */
export async function downloadFile(url: string, fileName?: string): Promise<void> {
  const response = await fetch(`${API_BASE}${url}`, {
    headers: { 'Authorization': `Bearer ${localStorage.getItem('token') || ''}` },
  })
  if (response.status === 401) {
    handleUnauthorized()
    throw new Error('未登录或登录已过期')
  }
  if (!response.ok) {
    let detail = `HTTP ${response.status}`
    try {
      const body = await response.json()
      if (body?.detail) detail = body.detail
    } catch {
      /* 非 JSON 错误体：沿用状态码提示 */
    }
    throw new Error(detail)
  }

  const blob = await response.blob()
  const objectUrl = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = objectUrl
  link.download = fileName || 'download'
  document.body.appendChild(link)
  link.click()
  link.remove()
  // 延迟释放：部分浏览器在 click 后立刻 revoke 会中断下载
  setTimeout(() => URL.revokeObjectURL(objectUrl), 10000)
}

/**
 * Send a message to the Agent and receive streaming response.
 */
export async function sendMessage(
  message: string,
  onResponse: (response: ChatResponse) => void,
  conversationId?: number,
  fileId?: string,
  signal?: AbortSignal,
): Promise<void> {
  const response = await fetch(`${API_BASE}/api/chat/message`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${localStorage.getItem('token') || ''}`,
    },
    body: JSON.stringify({
      conversation_id: conversationId ?? null,
      message,
      message_type: 'text',
      file_id: fileId || null,
    }),
    signal,
  })

  if (!response.ok) {
    throw new Error(`HTTP error! status: ${response.status}`)
  }

  const reader = response.body?.getReader()
  if (!reader) {
    throw new Error('No response body')
  }

  const decoder = new TextDecoder()
  let buffer = ''

  while (true) {
    const { done, value } = await reader.read()
    if (done) break

    buffer += decoder.decode(value, { stream: true })
    const lines = buffer.split('\n\n')
    buffer = lines.pop() || ''

    for (const line of lines) {
      if (line.startsWith('data: ')) {
        const data = line.slice(6)
        if (data === '[DONE]') continue
        try {
          const parsed = JSON.parse(data)
          onResponse(parsed)
        } catch (e) {
          console.error('Failed to parse SSE data:', data)
        }
      }
    }
  }

  // Flush remaining data in buffer (may not have been terminated by \n\n)
  if (buffer.trim()) {
    const remaining = buffer.trim()
    if (remaining.startsWith('data: ')) {
      const data = remaining.slice(6)
      if (data !== '[DONE]') {
        try {
          const parsed = JSON.parse(data)
          onResponse(parsed)
        } catch (e) {
          console.error('Failed to parse SSE data:', data)
        }
      }
    }
  }
}

